import { readFileSync, writeFileSync } from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';
import { createRaceDeskProjection } from '../race-desk/projection.mjs';

const defaultRoot = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '../..');

export function ensureRaceDeskLinks(repoRoot = defaultRoot, year = new Date().getUTCFullYear()) {
  const readJson = file => JSON.parse(readFileSync(path.join(repoRoot, file), 'utf8'));
  const projection = createRaceDeskProjection(readJson('data/race-desk/registry.v1.json'), readJson('scripts/deployment/sources.json'), year);
  const output = path.join(repoRoot, 'standings/core/race-desk-links.generated.js');
  const content = `// Generated by scripts/build/race-desk-links.mjs. Do not edit.\nexport default ${JSON.stringify(projection, null, 2)};\n`;
  let previous;
  try { previous = readFileSync(output, 'utf8'); } catch (error) { if (error.code !== 'ENOENT') throw error; }
  const changed = previous !== content;
  if (changed) writeFileSync(output, content);
  return { path: output, bytes: Buffer.byteLength(content), changed, buildYear: year };
}

if (process.argv[1] && path.resolve(process.argv[1]) === fileURLToPath(import.meta.url)) {
  console.log(JSON.stringify(ensureRaceDeskLinks()));
}
